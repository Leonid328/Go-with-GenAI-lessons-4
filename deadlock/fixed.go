// Package deadlock містить практичне застосування аналізу з
// Частини 2 домашньої роботи: той самий дедлок із завдання,
// але як тестована функція, яку потрібно виправити.
package deadlock

// Run повертає 42 від горутини через канал без дедлоку.
// WaitGroup тут не потрібен: достатньо прочитати з каналу,
// тоді send у горутині розблокується.
func Run() int {
	ch := make(chan int)
	go func() {
		ch <- 42
	}()
	return <-ch
}
